#pragma once

#include <stdint.h>

/*
 * bootloader 的日志串口。
 *
 * 硬件：USART4，**PB0 = TX**，115200 8N1（与应用固件的 COM1 同脚同参数，
 * 所以用同一根杜邦线 / 同一个 USB 串口模块就能看）。只发不收。
 *
 * 为什么不用 LED 表达状态：闪几下、闪多快在板子上很难看清，尤其是已经装进壳里
 * 或者灯被挡住的时候。串口一行文本能直接说出「为什么停在 bootloader」「哪个地址
 * 写失败」「收了多少块」，比灯靠谱得多。
 *
 * 输出是**阻塞轮询**的（bootloader 没有中断驱动 UART）：一行 40 字符在 115200 下
 * 约 3.5 ms。因此调用点都选在低频事件上（启动判定、每条错误、每 N 块进度），
 * 不要在每块/每字节的热路径里调用。
 *
 * 格式化只支持 %s %c %u %d %x %X %% 与宽度（如 %08x），不处理浮点。
 */
void boot_log_init(void);

void boot_log(const char *fmt, ...);
